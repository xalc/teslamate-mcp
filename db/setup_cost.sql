CREATE OR REPLACE VIEW teslamate_cost_mcp.charging_sessions AS
SELECT cp.id,
       cp.car_id,
       cp.start_date,
       cp.end_date,
       cp.duration_min,
       cp.charge_energy_added,
       cp.charge_energy_used,
       cp.cost,
       cp.start_battery_level,
       cp.end_battery_level,
       COALESCE(
         g.name,
         NULLIF(a.name, ''),
         NULLIF(
           concat_ws(
             ', ',
             NULLIF(concat_ws(' ', a.road, a.house_number), ''),
             a.city
           ),
           ''
         )
       ) AS address,
       g.name AS geofence,
       a.city AS city
FROM public.charging_processes cp
LEFT JOIN public.addresses a ON a.id = cp.address_id
LEFT JOIN public.geofences g ON g.id = cp.geofence_id;
ALTER VIEW teslamate_cost_mcp.charging_sessions OWNER TO teslamate;

