CREATE OR REPLACE VIEW teslamate_cost_mcp.toll_candidate_drives AS
SELECT d.id,
       d.car_id,
       d.start_date,
       d.end_date,
       d.distance,
       d.duration_min,
       sp.latitude AS start_latitude,
       sp.longitude AS start_longitude,
       ep.latitude AS end_latitude,
       ep.longitude AS end_longitude,
       COALESCE(
         sg.name,
         NULLIF(sa.name, ''),
         NULLIF(concat_ws(', ', NULLIF(concat_ws(' ', sa.road, sa.house_number), ''), sa.city), '')
       ) AS start_address,
       COALESCE(
         eg.name,
         NULLIF(ea.name, ''),
         NULLIF(concat_ws(', ', NULLIF(concat_ws(' ', ea.road, ea.house_number), ''), ea.city), '')
       ) AS end_address,
       sg.name AS start_geofence,
       sa.city AS start_city,
       eg.name AS end_geofence,
       ea.city AS end_city
FROM public.drives d
LEFT JOIN public.positions sp ON sp.id = d.start_position_id
LEFT JOIN public.positions ep ON ep.id = d.end_position_id
LEFT JOIN public.addresses sa ON sa.id = d.start_address_id
LEFT JOIN public.addresses ea ON ea.id = d.end_address_id
LEFT JOIN public.geofences sg ON sg.id = d.start_geofence_id
LEFT JOIN public.geofences eg ON eg.id = d.end_geofence_id;
ALTER VIEW teslamate_cost_mcp.toll_candidate_drives OWNER TO teslamate;

